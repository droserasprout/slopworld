"""Stage full upstream notices from the browser host's locked Linux graph."""

import json
import subprocess
from pathlib import Path
from typing import Any

from tools import ROOT
from tools.utils import run_main


def main() -> None:
    packages: dict[str, Any] = {}
    for target in ('x86_64-unknown-linux-gnu', 'aarch64-unknown-linux-gnu'):
        metadata = json.loads(
            subprocess.check_output(
                [
                    'cargo',
                    'metadata',
                    '--locked',
                    '--format-version',
                    '1',
                    '--filter-platform',
                    target,
                    '--manifest-path',
                    str(ROOT / 'slopweb/host/Cargo.toml'),
                ],
                text=True,
                cwd=ROOT,
            )
        )
        nodes = {node['id']: node for node in metadata['resolve']['nodes']}
        reached = set()
        pending = list(metadata['workspace_members'])
        while pending:
            identity = pending.pop()
            if identity not in reached:
                reached.add(identity)
                pending.extend(nodes[identity]['dependencies'])
        members = set(metadata['workspace_members'])
        packages.update((p['id'], p) for p in metadata['packages'] if p['id'] in reached - members)
    sections = [
        'Slopweb Rust host third-party notices',
        (
            'Generated by just generate-web-licenses from slopweb/host/Cargo.lock.\n'
            'Includes Linux x86_64/arm64 and development dependencies. All upstream\n'
            'root license and notice files are retained, including license alternatives.'
        ),
    ]
    for package in sorted(packages.values(), key=lambda p: (p['name'], p['version'])):
        source = Path(package['manifest_path']).parent
        notices = {
            p
            for p in source.iterdir()
            if p.is_file() and p.name.upper().startswith(('LICENSE', 'LICENCE', 'COPYING', 'NOTICE'))
        }
        if package.get('license_file'):
            notices.add(source / package['license_file'])
        if not notices:
            raise ValueError(f'Missing upstream license notices: {source.name}')
        header = f'{package["name"]} {package["version"]} — {package["license"]}'
        header += f'\nSource: https://crates.io/api/v1/crates/{package["name"]}/{package["version"]}/download'
        sections.append(header)
        for notice in sorted(notices):
            body = '\n'.join(line.rstrip() for line in notice.read_text().splitlines()).strip()
            sections.append(f'{notice.name}\n\n{body}')
    destination = ROOT / 'licenses/slopweb/THIRD-PARTY-NOTICES.txt'
    destination.parent.mkdir(parents=True, exist_ok=True)
    content = '\n\n'.join(sections) + '\n'
    if not destination.exists() or destination.read_text() != content:
        destination.write_text(content)
    print(f'Wrote {len(packages)} dependency notices to {destination.relative_to(ROOT)}')


if __name__ == '__main__':
    run_main(main)
