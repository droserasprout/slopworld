"""Bake consistently sized monochrome text-default symbols.

The pinned emoji-test data owns text-default scalar selection. Terminal columns
remain a runtime concern; this atlas supplies only font ink, never display widths.
"""

import subprocess

from PIL import Image
from PIL import ImageDraw
from PIL import ImageFont

from tools import ROOT
from tools.assets import emoji_atlas
from tools.assets.artwork import fit
from tools.assets.artwork import packed_ink_bounds
from tools.assets.artwork import png_bytes
from tools.generated_files import write_if_changed

FONT = ROOT / 'assets/fonts/noto-emoji-mono/NotoEmoji.ttf'
FONTS = (
    ROOT / 'assets/fonts/noto-symbols/NotoSansSymbols2-Regular.ttf',
    ROOT / 'assets/fonts/noto-symbols/NotoSansSymbols-Regular.ttf',
    FONT,
)
TEXTURE = ROOT / 'mod/Textures/SlopWorld/TerminalSymbols.png'
DATA = ROOT / 'mod/Source/SlopWorld/UI/Text/TextSymbolData.cs'
SIZE = 32
COLUMNS = 16
RASTER_SIZE = 96


def font_choices() -> dict[int, int]:
    """Resolve only against pinned files, never the host's fallback configuration."""
    choices: dict[int, int] = {}
    wanted = set(codepoints())
    for index, path in enumerate(FONTS):
        charset = subprocess.check_output(['fc-query', '--format=%{charset}', str(path)], text=True)
        for token in charset.split():
            ends = token.split('-')
            for cp in wanted:
                if int(ends[0], 16) <= cp <= int(ends[-1], 16):
                    choices.setdefault(cp, index)
    if choices.keys() != wanted:
        raise ValueError(f'missing text symbols: {sorted(wanted - choices.keys())}')
    return choices


def codepoints() -> list[int]:
    return sorted(
        {
            ord(key[0])
            for key in emoji_atlas.unicode_sequences(emoji_atlas.DEFAULT_SEQUENCES)
            if len(key) == 2 and key[1] == '\ufe0f'
        }
    )


def glyph(font: ImageFont.FreeTypeFont, cp: int) -> tuple[Image.Image, tuple[int, int, int, int]]:
    text = chr(cp)
    left, top, right, bottom = font.getbbox(text, anchor='ls')
    probe = Image.new('RGBA', (int(right - left), int(bottom - top)))
    ImageDraw.Draw(probe).text((-left, -top), text, font=font, anchor='ls', fill='white')
    ink = probe.getchannel('A').getbbox()
    if ink is None:
        raise ValueError(f'empty symbol: {cp:X}')
    x, y, r, b = ink
    return probe.crop(ink), (int(left) + x, int(top) + y, r - x, b - y)


def data_source(
    points: list[int], ink_bounds: list[int], font_bounds: list[tuple[int, int, int, int]], sources: list[int]
) -> str:
    values = ', '.join(f'0x{cp:X}' for cp in points)
    rows = (len(points) + COLUMNS - 1) // COLUMNS
    ink_values = ', '.join(f'0x{bounds:08X}' for bounds in ink_bounds)
    metric_values = ', '.join(str(value) for bounds in font_bounds for value in bounds)
    source_values = ', '.join(str(value) for value in sources)
    return f"""// Generated by tools/assets/symbol_atlas.py. Do not edit by hand.
namespace SlopWorld
{{
    static class TextSymbolData
    {{
        public const int AtlasColumns = {COLUMNS};
        public const int AtlasRows = {rows};
        public const int CellSize = {SIZE};
        public const int RasterSize = {RASTER_SIZE};
        public static readonly int[] Codepoints = new int[] {{ {values} }};
        public static readonly uint[] InkBounds = new uint[] {{ {ink_values} }};
        // Original x/y bearings and ink width/height at RasterSize, relative to baseline.
        public static readonly int[] FontBounds = new int[] {{ {metric_values} }};
        // Sources: 0 = Noto Sans Symbols 2, 1 = Noto Sans Symbols, 2 = Noto Emoji.
        public static readonly byte[] FontSources = new byte[] {{ {source_values} }};
    }}
}}
"""


def main() -> None:
    fonts = [ImageFont.truetype(str(path), RASTER_SIZE) for path in FONTS]
    choices = font_choices()
    points = codepoints()
    ink_bounds = []
    font_bounds = []
    atlas = Image.new('RGBA', (COLUMNS * SIZE, ((len(points) + COLUMNS - 1) // COLUMNS) * SIZE))
    for slot, cp in enumerate(points):
        probe, metrics = glyph(fonts[choices[cp]], cp)
        font_bounds.append(metrics)
        cell = fit(probe, SIZE, breathe=1.08)
        ink_bounds.append(packed_ink_bounds(cell))
        atlas.paste(cell, ((slot % COLUMNS) * SIZE, (slot // COLUMNS) * SIZE))
    write_if_changed(TEXTURE, png_bytes(atlas))
    sources = [choices[cp] for cp in points]
    write_if_changed(DATA, data_source(points, ink_bounds, font_bounds, sources).encode())
    print(f'wrote {len(points)} monochrome font symbols: {[sources.count(i) for i in range(len(FONTS))]}')


if __name__ == '__main__':
    main()
